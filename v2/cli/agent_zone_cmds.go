func newAgentZoneDsyncStatusCmd(kind string) *cobra.Command {
	c := &cobra.Command{
		Use:   "status",
		Short: "Send dsync status command to tdns-auth",
		Run: func(cmd *cobra.Command, args []string) {
			tdnscli.PrepArgs("zonename")

			api, err := GetApiClientForCmd(cmd, true)
			if err != nil {
				log.Fatalf("Error getting API client: %v", err)
			}

			resp, err := tdnscli.SendDsyncCommand(api, tdns.ZoneDsyncPost{
				Command: "status",
				Zone:    dns.Fqdn(tdns.Globals.Zonename),
			})

			if err != nil {
				fmt.Printf("Error: %s\n", err.Error())
				os.Exit(1)
			}
			if resp.Error {
				fmt.Printf("Error from tdns-auth: %s\n", resp.ErrorMsg)
				os.Exit(1)
			}

			if resp.Msg != "" {
				fmt.Printf("%s\n", resp.Msg)
			}
			out := []string{}
			for key, status := range resp.Functions {
				out = append(out, fmt.Sprintf("%s|%s", key, status))
			}

			sort.Strings(out)
			if tdns.Globals.ShowHeaders {
				out = append([]string{"Function|Status"}, out...)
			}

			fmt.Printf("%s\n", columnize.SimpleFormat(out))
			if len(resp.Todo) > 0 {
				fmt.Printf("\nTODO:\n")
				for _, todo := range resp.Todo {
					fmt.Printf("--> %s\n", todo)
				}
			}
		},
	}
	return c
}

