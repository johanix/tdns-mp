// tdnsZoneListCmd is tdns's "zone list" leaf, lifted out of a fresh
// tdnscli.NewZoneCmd(role) so that it keeps the -f/-N/-P flags, which are
// bound to variables private to the tdns cli package that RunZoneList
// reads. It was the one leaf of tdns's static AgentZoneCmd that mp had no
// copy of.
func tdnsZoneListCmd(role string) *cobra.Command {
	tmp := tdnscli.NewZoneCmd(role)
	for _, sub := range tmp.Commands() {
		if sub.Name() == "list" {
			tmp.RemoveCommand(sub)
			return sub
		}
	}
	panic("tdnscli.NewZoneCmd has no \"list\" leaf")
}
